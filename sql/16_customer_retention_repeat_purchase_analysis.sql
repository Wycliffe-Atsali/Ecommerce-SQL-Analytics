/*

Analyst Observations
--------------------

• Customer retention is a critical driver of sustainable business growth.

• One-time customers contribute a significant proportion of total revenue,
  indicating strong customer acquisition but also highlighting an opportunity
  to improve repeat purchasing behaviour.

• Segmenting customers into One-Time, Repeat and Loyal groups enables more
  targeted marketing strategies and performance monitoring.

• Average customer revenue provides a better measure of customer value than
  average payment value because it reflects total spending per customer.

Business Recommendations
------------------------

1. Introduce second-purchase incentives to encourage newly acquired customers
   to make another purchase.

2. Implement loyalty programmes that reward repeat purchases with discounts,
   reward points or exclusive benefits.

3. Launch personalised email and SMS campaigns recommending complementary
   products shortly after a customer's first purchase.

4. Continuously monitor customer retention KPIs such as:
      - Repeat Purchase Rate
      - Average Orders per Customer
      - Revenue by Customer Segment
      - Customer Lifetime Value (CLV)

5. Use customer segmentation to tailor marketing campaigns according to
   purchasing behaviour rather than applying a single strategy to all
   customers.

