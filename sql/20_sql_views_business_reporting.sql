BUSINESS OBJECTIVE
------------------
This investigation introduces SQL Views as persistent database objects that
store reusable SQL queries. Unlike Common Table Expressions (CTEs), Views
remain stored in the database and can be queried repeatedly without rewriting
complex joins and aggregations.

The investigation demonstrates how Views simplify business reporting by
encapsulating commonly used analytical queries such as customer revenue,
seller revenue, category revenue, and monthly revenue.

-------------------------------------------------------------------------------

LEARNING OBJECTIVES
-------------------
• Understand the purpose of SQL Views.
• Create reusable Views using CREATE VIEW.
• Query Views as if they were regular database tables.
• Compare Views with Subqueries and CTEs.
• Design reusable business reporting objects.
• Prepare datasets suitable for Business Intelligence dashboards.

-------------------------------------------------------------------------------

VIEW CREATION STRATEGY
----------------------

During development, CREATE OR REPLACE VIEW is used to safely update existing
Views without manually dropping them.

Example:

CREATE OR REPLACE VIEW customer_revenue_view AS
...

In production environments, Views are typically created once during database
deployment and reused indefinitely.

