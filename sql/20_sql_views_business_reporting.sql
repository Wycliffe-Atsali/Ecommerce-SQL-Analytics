/*
Question 14
CTEs vs Views

Common Table Expressions (CTEs)

• Exist only for the duration of a single query.
• Created using the WITH keyword.
• Excellent for breaking complex queries into readable steps.
• Cannot be reused after the query completes.

Views

• Persist as database objects.
• Created once using CREATE VIEW (or CREATE OR REPLACE VIEW).
• Can be queried repeatedly by multiple users.
• Ideal for reusable business reports and BI dashboards.

Development Note

During development, CREATE OR REPLACE VIEW is the preferred approach because
it updates an existing View without requiring it to be dropped manually.

Alternative approaches include:

DROP VIEW IF EXISTS view_name;
CREATE VIEW view_name AS ...

This is useful when changing the View structure in ways that
CREATE OR REPLACE VIEW cannot accommodate.

For production systems:

• CREATE VIEW is typically executed once during deployment.
• Analysts then query the View directly without recreating it.
*/


