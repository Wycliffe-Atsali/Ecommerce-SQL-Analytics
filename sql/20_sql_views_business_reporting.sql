/*=============================================================================
SECTION 2 — CATEGORY AND MONTHLY REPORTING VIEWS
=============================================================================*/


/*-----------------------------------------------------------------------------
Question 9
Business Question:
Create a View that summarises total revenue generated by each product category.
-----------------------------------------------------------------------------*/

CREATE OR REPLACE VIEW category_revenue_view AS
SELECT
    p.product_category_name AS category,
    SUM(oi.price) AS revenue
FROM order_items oi
JOIN products p
    ON oi.product_id = p.product_id
GROUP BY category;


/*-----------------------------------------------------------------------------
Question 10
Business Question:
Identify product categories whose revenue is above the average category revenue.
-----------------------------------------------------------------------------*/

SELECT *
FROM category_revenue_view
WHERE revenue >
(
    SELECT AVG(revenue)
    FROM category_revenue_view
)
ORDER BY revenue DESC;


/*-----------------------------------------------------------------------------
Question 11
Business Question:
Create a View that summarises monthly sales revenue.
-----------------------------------------------------------------------------*/

CREATE OR REPLACE VIEW monthly_revenue_view AS
SELECT
    DATE_TRUNC('month', o.order_purchase_timestamp) AS purchase_month,
    SUM(op.payment_value) AS revenue
FROM order_payments op
JOIN orders o
    ON op.order_id = o.order_id
GROUP BY purchase_month;


/*-----------------------------------------------------------------------------
Question 12
Business Question:
Identify months whose revenue exceeded the average monthly revenue.
-----------------------------------------------------------------------------*/

SELECT *
FROM monthly_revenue_view
WHERE revenue >
(
    SELECT AVG(revenue)
    FROM monthly_revenue_view
)
ORDER BY purchase_month;


