SECTION 1 — VIEW CREATION
=============================================================================*/


/*-----------------------------------------------------------------------------
Question 1
Business Question:
Create a View that calculates total revenue generated by each customer.
-----------------------------------------------------------------------------*/

CREATE OR REPLACE VIEW customer_revenue_view AS
SELECT
    c.customer_unique_id AS customer,
    SUM(op.payment_value) AS revenue
FROM order_payments op
JOIN orders o
    ON op.order_id = o.order_id
JOIN customers c
    ON o.customer_id = c.customer_id
GROUP BY customer;


/*-----------------------------------------------------------------------------
Question 2
Business Question:
Retrieve all customer revenue records using the View.
-----------------------------------------------------------------------------*/

SELECT *
FROM customer_revenue_view;


/*-----------------------------------------------------------------------------
Question 3
Business Question:
Identify customers whose revenue exceeds the average customer revenue.
-----------------------------------------------------------------------------*/

SELECT *
FROM customer_revenue_view
WHERE revenue >
(
    SELECT AVG(revenue)
    FROM customer_revenue_view
)
ORDER BY revenue DESC;


/*-----------------------------------------------------------------------------
Question 4
Business Question:
Display the Top 10 highest-spending customers.
-----------------------------------------------------------------------------*/

SELECT *
FROM customer_revenue_view
ORDER BY revenue DESC
LIMIT 10;


/*-----------------------------------------------------------------------------
Question 5
Business Question:
Create a View that summarises seller revenue.
