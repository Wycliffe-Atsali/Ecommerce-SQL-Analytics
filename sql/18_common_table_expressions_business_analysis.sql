BUSINESS OBJECTIVE
------------------
This investigation introduces Common Table Expressions (CTEs) as a powerful
technique for simplifying complex SQL queries.

Rather than repeating the same aggregations multiple times, CTEs allow
intermediate result sets to be defined once and reused throughout a query,
improving readability, maintainability, and scalability.

The investigation focuses on identifying high-performing customers, sellers,
product categories, and sales periods using reusable business summaries.

