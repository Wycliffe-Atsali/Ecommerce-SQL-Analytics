Question 1
Business Question:
Create a reusable CTE that calculates total revenue generated by each customer.
=============================================================================*/

WITH customer_revenue AS
(
    SELECT
        c.customer_unique_id AS customer,
        SUM(op.payment_value) AS revenue
    FROM order_payments op
    JOIN orders o
        ON op.order_id = o.order_id
    JOIN customers c
        ON o.customer_id = c.customer_id
    GROUP BY customer
);


/*=============================================================================
Question 2
Business Question:
Identify customers whose revenue exceeds the average customer revenue.
=============================================================================*/

WITH customer_revenue AS
(
    SELECT
        c.customer_unique_id AS customer,
        SUM(op.payment_value) AS revenue
    FROM order_payments op
    JOIN orders o
        ON op.order_id = o.order_id
    JOIN customers c
        ON o.customer_id = c.customer_id
    GROUP BY customer
)

SELECT *
FROM customer_revenue
WHERE revenue >
(
    SELECT AVG(revenue)
    FROM customer_revenue
)
ORDER BY revenue DESC;


