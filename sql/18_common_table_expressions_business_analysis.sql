Question 4
Business Question:
Summarise customer revenue by calculating the average, highest,
and lowest customer revenue.
=============================================================================*/

WITH customer_revenue AS
(
    SELECT
        c.customer_unique_id AS customer,
        SUM(op.payment_value) AS revenue
    FROM order_payments op
    JOIN orders o
        ON op.order_id = o.order_id
    JOIN customers c
        ON o.customer_id = c.customer_id
    GROUP BY customer
)

SELECT
    ROUND(AVG(revenue), 2) AS average_customer_revenue,
    MAX(revenue) AS highest_customer_revenue,
    MIN(revenue) AS lowest_customer_revenue
FROM customer_revenue;


