/*==============================================================================
Question 1
Define and validate the analytical customer population.
==============================================================================*/

WITH population AS
(
    SELECT
        c.customer_unique_id AS customer,
        COUNT(DISTINCT o.order_id) AS delivered_orders,
        MIN(o.order_purchase_timestamp) AS first_purchase_date,
        MAX(o.order_purchase_timestamp) AS latest_purchase_date

    FROM customers c

    JOIN orders o
        ON o.customer_id = c.customer_id

    WHERE o.order_status = 'delivered'

    GROUP BY c.customer_unique_id
)

SELECT
    COUNT(*) AS analytical_customers,
    SUM(delivered_orders) AS delivered_orders,
    MIN(first_purchase_date) AS earliest_purchase,
    MAX(latest_purchase_date) AS latest_purchase

FROM population;


/*==============================================================================
Question 2
Calculate historical lifetime revenue generated by every customer.
==============================================================================*/

SELECT
    c.customer_unique_id AS customer,
    SUM(op.payment_value) AS lifetime_revenue

FROM customers c

JOIN orders o
    ON o.customer_id = c.customer_id

JOIN order_payments op
    ON op.order_id = o.order_id

WHERE o.order_status = 'delivered'

GROUP BY c.customer_unique_id

ORDER BY lifetime_revenue DESC;


/*==============================================================================
Question 3
Calculate purchase frequency and Average Order Value (AOV).
==============================================================================*/

WITH customer_metrics AS
(
    SELECT
        c.customer_unique_id AS customer,
        COUNT(DISTINCT o.order_id) AS order_frequency,
        SUM(op.payment_value) AS lifetime_revenue

    FROM customers c

    JOIN orders o
        ON o.customer_id = c.customer_id

    JOIN order_payments op
        ON op.order_id = o.order_id

    WHERE o.order_status = 'delivered'

    GROUP BY c.customer_unique_id
)

SELECT
    customer,
    order_frequency,

    ROUND(
        (
            lifetime_revenue
            /
            NULLIF(order_frequency, 0)
        )::numeric,
        2
    ) AS avg_order_value,

    ROUND(lifetime_revenue::numeric, 2) AS lifetime_revenue

FROM customer_metrics

ORDER BY lifetime_revenue DESC;


