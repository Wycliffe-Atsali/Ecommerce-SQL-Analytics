SQL Dialect:
PostgreSQL

Analytical Framework
--------------------
Population:
    Customers with at least one delivered order.

Grain:
    One row per customer_unique_id.

Revenue:
    SUM(order_payments.payment_value) for delivered orders.

Normalization:
    PERCENT_RANK() * 100

Base Customer Value Score:
    Revenue       40%
    Frequency     25%
    AOV           20%
    Lifespan      15%

Customer Value Tiers:
    VIP          >= 90
    High Value   >= 75
    Growth       >= 60
    Standard     >= 40
    Low Value    < 40

Business Objective:
Develop a historical customer-value framework that combines realised
revenue, purchasing frequency, average order value and purchasing lifespan
into a normalized and weighted Customer Value Score.

Important Scope Note:
This is a historical realised-value model, not a predictive CLV model.
It does not forecast future customer revenue, churn probability or future
customer lifespan.
