    END;


/*==============================================================================
Question 15
Build the final reusable Customer Value Dashboard.

The view is the authoritative analytical output for Investigation 34.
==============================================================================*/

DROP VIEW IF EXISTS customer_value_dashboard;

CREATE VIEW customer_value_dashboard AS

WITH base AS
(
    SELECT
        c.customer_unique_id AS customer,

        SUM(op.payment_value) AS lifetime_revenue,

        COUNT(DISTINCT o.order_id) AS order_frequency,

        SUM(op.payment_value)
        /
        NULLIF(COUNT(DISTINCT o.order_id), 0)
            AS avg_order_value,

        MIN(o.order_purchase_timestamp)
            AS first_purchase_date,

        MAX(o.order_purchase_timestamp)
            AS latest_purchase_date,

        EXTRACT(
            EPOCH FROM
            (
                MAX(o.order_purchase_timestamp)
                -
                MIN(o.order_purchase_timestamp)
            )
        ) / 86400.0
            AS purchasing_lifespan_days

    FROM customers c

    JOIN orders o
        ON o.customer_id = c.customer_id

    JOIN order_payments op
        ON op.order_id = o.order_id

    WHERE o.order_status = 'delivered'

    GROUP BY c.customer_unique_id
),

normalized AS
(
    SELECT
        *,

        PERCENT_RANK()
        OVER (ORDER BY lifetime_revenue) * 100
            AS revenue_score,

        PERCENT_RANK()
        OVER (ORDER BY order_frequency) * 100
            AS frequency_score,

        PERCENT_RANK()
        OVER (ORDER BY avg_order_value) * 100
            AS aov_score,

        PERCENT_RANK()
        OVER (ORDER BY purchasing_lifespan_days) * 100
            AS lifespan_score

    FROM base
),

scored AS
(
    SELECT
        *,

        revenue_score * 0.40
        + frequency_score * 0.25
        + aov_score * 0.20
        + lifespan_score * 0.15
            AS customer_value_score,

        revenue_score * 0.50
        + frequency_score * 0.20
        + aov_score * 0.20
        + lifespan_score * 0.10
            AS economic_contribution_score,

        revenue_score * 0.30
        + frequency_score * 0.30
        + aov_score * 0.15
        + lifespan_score * 0.25
            AS relationship_oriented_score

    FROM normalized
),

ranked AS
(
    SELECT
        *,

        RANK()
        OVER (
            ORDER BY lifetime_revenue DESC
        ) AS revenue_rank,

        RANK()
        OVER (
            ORDER BY customer_value_score DESC
        ) AS customer_value_rank

    FROM scored
)

SELECT
    customer,

    ROUND(lifetime_revenue::numeric, 2)
        AS lifetime_revenue,

    order_frequency,

    ROUND(avg_order_value::numeric, 2)
        AS avg_order_value,

    first_purchase_date,
    latest_purchase_date,

    ROUND(purchasing_lifespan_days::numeric, 2)
        AS purchasing_lifespan_days,

    ROUND(revenue_score::numeric, 2)
        AS revenue_score,

    ROUND(frequency_score::numeric, 2)
        AS frequency_score,

    ROUND(aov_score::numeric, 2)
        AS aov_score,

    ROUND(lifespan_score::numeric, 2)
        AS lifespan_score,

    ROUND(customer_value_score::numeric, 2)
        AS customer_value_score,

    CASE
        WHEN customer_value_score >= 90 THEN 'VIP'
        WHEN customer_value_score >= 75 THEN 'High Value'
        WHEN customer_value_score >= 60 THEN 'Growth'
        WHEN customer_value_score >= 40 THEN 'Standard'
        ELSE 'Low Value'
    END AS customer_value_tier,

    revenue_rank,
    customer_value_rank,

    ROUND(economic_contribution_score::numeric, 2)
        AS economic_contribution_score,

    ROUND(relationship_oriented_score::numeric, 2)
        AS relationship_oriented_score

FROM ranked;
