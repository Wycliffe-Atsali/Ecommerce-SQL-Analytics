SELECT
    tier AS customer_value_tier,
    COUNT(*) AS customers,

    ROUND(
        (
            COUNT(*) * 100.0
            /
            SUM(COUNT(*)) OVER ()
        )::numeric,
        2
    ) AS customer_percentage,

    ROUND(SUM(revenue)::numeric, 2) AS total_revenue,

    ROUND(
        (
            SUM(revenue) * 100.0
            /
            SUM(SUM(revenue)) OVER ()
