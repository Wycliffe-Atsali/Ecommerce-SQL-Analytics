/*
===============================================================================
QUESTION 9
Average Installments by Payment Method
===============================================================================

Business Question
-----------------
What is the average number of installments used for each payment method?

*/

SELECT

    payment_type AS payment_method,

    ROUND(

        AVG(payment_installments),

        2

    ) AS average_installments

FROM order_payments

GROUP BY payment_method

ORDER BY average_installments DESC;



/*
===============================================================================
QUESTION 10
Maximum Installments by Payment Method
===============================================================================

Business Question
-----------------
What is the highest installment count recorded for each payment method?

*/

SELECT

    payment_type AS payment_method,

    MAX(payment_installments)
        AS maximum_installments

FROM order_payments

GROUP BY payment_method

ORDER BY maximum_installments DESC;



/*
===============================================================================
QUESTION 11
Single-Installment Payments
===============================================================================

Business Question
-----------------
How many payment records were completed using a single installment?

*/

SELECT

    COUNT(*) AS payment_records_with_single_installment

FROM order_payments

WHERE payment_installments = 1;



/*
===============================================================================
QUESTION 12
Multiple-Installment Payments
===============================================================================

Business Question
-----------------
How many payment records were completed using more than one installment?

*/

SELECT

    COUNT(*) AS payment_records_with_multiple_installments

FROM order_payments

WHERE payment_installments > 1;



