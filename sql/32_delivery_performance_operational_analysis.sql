-- =============================================================================
-- Question 1
-- Calculate the average delivery duration for each seller.
-- =============================================================================

WITH seller_delivery AS
(
    SELECT
        oi.seller_id AS seller,
        ROUND(
            AVG(
                EXTRACT(
                    EPOCH FROM (
                        o.order_delivered_customer_date
                        - o.order_purchase_timestamp
                    )
                ) / 86400
            ),
            2
        ) AS avg_delivery_days
    FROM order_items oi
    JOIN orders o
        ON oi.order_id = o.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY oi.seller_id
)

SELECT *
FROM seller_delivery
ORDER BY avg_delivery_days;

-- =============================================================================
-- Question 2
-- Calculate the average delivery delay for late deliveries.
-- =============================================================================

WITH seller_delivery_delay AS
(
    SELECT
        oi.seller_id AS seller,
        ROUND(
            AVG(
                EXTRACT(
                    EPOCH FROM (
                        o.order_delivered_customer_date -
                        o.order_estimated_delivery_date
                    )
                ) / 86400
            ),
            2
        ) AS avg_delivery_delay
    FROM order_items oi
    JOIN orders o
        ON oi.order_id = o.order_id
    WHERE o.order_status = 'delivered'
      AND o.order_estimated_delivery_date <
          o.order_delivered_customer_date
    GROUP BY oi.seller_id
)

SELECT *
FROM seller_delivery_delay
ORDER BY avg_delivery_delay;

-- =============================================================================
-- Question 3
-- Calculate the percentage of on-time deliveries for every seller.
-- =============================================================================

WITH total_orders AS
(
    SELECT
        oi.seller_id AS seller,
        COUNT(DISTINCT o.order_id) AS total_orders
    FROM order_items oi
    JOIN orders o
        ON oi.order_id = o.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY oi.seller_id
),

orders_on_time AS
(
    SELECT
        oi.seller_id AS seller,
        COUNT(DISTINCT o.order_id) AS on_time
    FROM order_items oi
    JOIN orders o
        ON oi.order_id = o.order_id
    WHERE o.order_status = 'delivered'
      AND o.order_delivered_customer_date
          <= o.order_estimated_delivery_date
    GROUP BY oi.seller_id
),

delivery_time_analysis AS
(
    SELECT
        tor.seller,
        tor.total_orders,
        COALESCE(oot.on_time, 0) AS on_time,

        ROUND(
            COALESCE(oot.on_time, 0)::NUMERIC
            /
            tor.total_orders
            * 100,
            2
        ) AS on_time_percentage

    FROM total_orders tor

    LEFT JOIN orders_on_time oot
        ON tor.seller = oot.seller
)

SELECT *
FROM delivery_time_analysis;

-- =============================================================================
-- Question 4
-- Calculate the average customer review score for each seller.
-- =============================================================================

WITH seller_reviews AS
(
    SELECT

        oi.seller_id AS seller,
        ROUND(
            AVG(orv.review_score),
            2
        ) AS average_review_score
    FROM order_items AS oi
    JOIN orders AS o
        ON oi.order_id = o.order_id
    JOIN order_reviews AS orv
        ON oi.order_id = orv.order_id
    WHERE
        o.order_status = 'delivered'
    GROUP BY
        oi.seller_id
)

SELECT *
FROM seller_reviews;

