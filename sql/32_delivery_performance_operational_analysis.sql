    JOIN seller_reviews srv
        ON sd.seller=srv.seller
    JOIN seller_freight_charges sfc
        ON sd.seller=sfc.seller
),

kpi_standardization AS
(
    SELECT
        seller,

        on_time_score,

        NTILE(100)
        OVER(
            ORDER BY avg_delivery_days DESC
        ) AS delivery_score,

        ROUND(
            (average_review_score/5)*100,
            2
        ) AS review_score,

        NTILE(100)
        OVER(
            ORDER BY average_freight_cost DESC
        ) AS freight_score

    FROM delivery_performance_summary
),

weighted_kpi AS
(
    SELECT
        seller,

        ROUND(0.40*on_time_score,2) AS w_on_time,
        ROUND(0.25*delivery_score,2) AS w_delivery,
        ROUND(0.20*review_score,2) AS w_review,
        ROUND(0.15*freight_score,2) AS w_freight,

        (
            ROUND(0.40*on_time_score,2)+
            ROUND(0.25*delivery_score,2)+
            ROUND(0.20*review_score,2)+
            ROUND(0.15*freight_score,2)
        ) AS delivery_summary

    FROM kpi_standardization
)

SELECT *
FROM weighted_kpi;


