Question 6
Average delivery time by customer state
==============================================================*/

WITH state_delivery AS
(
    SELECT
        c.customer_state,
        ROUND(
            AVG(
                EXTRACT(
                    EPOCH FROM
                    (
                        o.order_delivered_customer_date -
                        o.order_purchase_timestamp
                    )
                ) / 86400
            ),
            2
        ) AS avg_delivery_days
