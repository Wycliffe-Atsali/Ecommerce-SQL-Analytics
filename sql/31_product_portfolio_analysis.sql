WITH product_revenue AS
(
    SELECT
        product_id AS product,
        SUM(price) AS revenue
    FROM order_items
    GROUP BY product_id
),

product_sales AS
(
    SELECT
        product_id AS product,
        COUNT(*) AS units_sold
    FROM order_items
    GROUP BY product_id
),

product_reviews AS
(
    SELECT
        oi.product_id AS product,
        ROUND(AVG(orv.review_score),2) AS review_score
    FROM order_items oi
    JOIN order_reviews orv
        ON oi.order_id = orv.order_id
    GROUP BY oi.product_id
),

product_freight AS
(
    SELECT
        product_id AS product,
        ROUND(AVG(freight_value),2) AS average_freight_cost
    FROM order_items
    GROUP BY product_id
),

category_performance AS
(
    SELECT
        p.product_id AS product,

        NTILE(100) OVER
        (
            PARTITION BY p.product_category_name
            ORDER BY SUM(oi.price) ASC
        ) AS category_score

    FROM products p

    JOIN order_items oi
        ON p.product_id = oi.product_id

    GROUP BY
        p.product_id,
        p.product_category_name
)

SELECT

    pr.product,

    pr.revenue,

    ps.units_sold,

    prev.review_score,

    pf.average_freight_cost,

    cp.category_score

FROM product_revenue pr

JOIN product_sales ps
    ON pr.product = ps.product

JOIN product_reviews prev
    ON pr.product = prev.product

JOIN product_freight pf
    ON pr.product = pf.product

JOIN category_performance cp
    ON pr.product = cp.product

ORDER BY revenue DESC;



-- =============================================================================
-- QUESTION 12
-- Standardize KPIs into a common 1–100 scoring framework and calculate the
-- weighted Product Performance Score.
--
-- Weighting Model
--
-- Revenue................35%
-- Units Sold.............25%
-- Customer Reviews.......20%
-- Freight Efficiency.....10%
-- Category Performance...10%
-- =============================================================================

WITH product_summary AS
(
    SELECT
        pr.product,
        pr.revenue,
        ps.units_sold,
        prev.review_score,
        pf.average_freight_cost,
        cp.category_score

    FROM
    (
        SELECT product_id AS product,
               SUM(price) AS revenue
        FROM order_items
        GROUP BY product_id
    ) pr

    JOIN
    (
        SELECT product_id AS product,
               COUNT(*) AS units_sold
        FROM order_items
        GROUP BY product_id
    ) ps
        ON pr.product = ps.product

    JOIN
    (
        SELECT
            oi.product_id AS product,
            ROUND(AVG(orv.review_score),2) AS review_score
        FROM order_items oi
        JOIN order_reviews orv
            ON oi.order_id = orv.order_id
        GROUP BY oi.product_id
    ) prev
        ON pr.product = prev.product

    JOIN
    (
        SELECT
            product_id AS product,
            ROUND(AVG(freight_value),2) AS average_freight_cost
        FROM order_items
        GROUP BY product_id
    ) pf
        ON pr.product = pf.product

    JOIN
    (
        SELECT
            p.product_id AS product,

            NTILE(100) OVER
            (
                PARTITION BY p.product_category_name
                ORDER BY SUM(oi.price) ASC
            ) AS category_score

        FROM products p

        JOIN order_items oi
            ON p.product_id = oi.product_id

        GROUP BY
            p.product_id,
            p.product_category_name
    ) cp
        ON pr.product = cp.product
),

product_report AS
(
    SELECT

        product,

        NTILE(100) OVER
        (
            ORDER BY revenue ASC
        ) AS revenue_score,

        NTILE(100) OVER
        (
            ORDER BY units_sold ASC
        ) AS sales_score,

        ROUND((review_score / 5.0) * 100,2) AS review_score,

        NTILE(100) OVER
        (
            ORDER BY average_freight_cost DESC
        ) AS freight_score,

        category_score

    FROM product_summary
),

weighted_scorecard AS
(
    SELECT

        product,

        ROUND(revenue_score * 0.35,2) AS weighted_revenue,

        ROUND(sales_score * 0.25,2) AS weighted_sales,

        ROUND(review_score * 0.20,2) AS weighted_reviews,

        ROUND(freight_score * 0.10,2) AS weighted_freight,

        ROUND(category_score * 0.10,2) AS weighted_category,

        ROUND
        (
              revenue_score * 0.35
            + sales_score * 0.25
            + review_score * 0.20
            + freight_score * 0.10
            + category_score * 0.10
        ,2) AS product_performance_score

    FROM product_report
)

SELECT *

FROM weighted_scorecard

ORDER BY product_performance_score DESC;



