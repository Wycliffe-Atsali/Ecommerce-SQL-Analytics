-- ============================================================================
-- QUESTION 1
-- Calculate the total revenue generated by each product.
-- Revenue is calculated using the product selling price
-- (order_items.price) rather than payment value.
-- ============================================================================

WITH product_revenue AS
(
    SELECT
        product_id AS product,
        SUM(price) AS total_revenue
    FROM order_items
    GROUP BY product
)

SELECT *
FROM product_revenue
ORDER BY total_revenue DESC;

-- ============================================================================
-- QUESTION 2
-- Calculate the total number of units sold for each product.
-- This measures overall customer demand.
-- ============================================================================

WITH product_sales AS
(
    SELECT
        product_id AS product,
        COUNT(product_id) AS units_sold
    FROM order_items
    GROUP BY product
)

SELECT *
FROM product_sales
ORDER BY units_sold DESC;

-- ============================================================================
-- QUESTION 3
-- Calculate the average customer review score for each product.
-- Higher review scores indicate greater customer satisfaction.
-- ============================================================================

WITH product_reviews AS
(
    SELECT
        oi.product_id AS product,
        ROUND(
            AVG(orv.review_score),
            2
        ) AS average_review_score
    FROM order_items oi

    JOIN order_reviews orv
        ON oi.order_id = orv.order_id

    GROUP BY product
)

SELECT *
FROM product_reviews
ORDER BY average_review_score DESC;

-- ============================================================================
-- QUESTION 4
-- Calculate the average freight cost for each product.
-- Freight cost will later be treated as a negative KPI, where lower
-- shipping costs contribute positively to the overall performance score.
-- ============================================================================

WITH product_freight AS
(
    SELECT
        product_id AS product,
        ROUND(
            AVG(freight_value),
            2
        ) AS average_freight_cost
    FROM order_items
    GROUP BY product
)

SELECT *
FROM product_freight
ORDER BY average_freight_cost ASC;

-- ============================================================================
-- QUESTION 5A
-- Retrieve the product category assigned to every product.
-- This mapping will be used later when calculating category-relative
-- performance scores.
-- ============================================================================

WITH product_categories AS
(
    SELECT
        product_id AS product,
        product_category_name AS category
    FROM products
)

SELECT *
FROM product_categories
ORDER BY category;

-- ============================================================================
-- QUESTION 5B
-- Calculate the total number of products available within each category.
-- This provides an overview of catalogue distribution across the marketplace.
-- ============================================================================

WITH category_product_counts AS
(
    SELECT
        product_category_name AS category,
        COUNT(DISTINCT product_id) AS total_products
    FROM products
    GROUP BY category
)

SELECT *
FROM category_product_counts
ORDER BY total_products DESC;

