-- QUESTION 6
-- Calculate the average revenue generated per sale for each product.
-- This metric measures the average selling value whenever a product is sold.
-- ============================================================================

WITH product_revenue AS
(
    SELECT
        product_id AS product,
        SUM(price) AS total_revenue
    FROM order_items
    GROUP BY product
),

product_sales AS
(
    SELECT
        product_id AS product,
        COUNT(*) AS units_sold
    FROM order_items
    GROUP BY product
),

average_revenue_per_sale AS
(
    SELECT
        pr.product,
        pr.total_revenue,
        ps.units_sold,

        ROUND(
            pr.total_revenue /
            ps.units_sold,
            2
        ) AS average_revenue_per_sale

    FROM product_revenue pr

    JOIN product_sales ps
        ON pr.product = ps.product
)

SELECT *
FROM average_revenue_per_sale
ORDER BY average_revenue_per_sale DESC;


