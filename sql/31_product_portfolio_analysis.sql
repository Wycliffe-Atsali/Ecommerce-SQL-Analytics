INVESTIGATION SUMMARY

The Product Portfolio Analysis extends beyond traditional sales reporting by
evaluating products across multiple business dimensions.

Rather than relying solely on revenue, products are assessed using a balanced
scorecard incorporating:

• Financial Performance (Revenue)
• Market Demand (Units Sold)
• Customer Satisfaction (Review Score)
• Operational Efficiency (Freight Cost)
• Competitive Positioning (Category Performance)

To enable meaningful comparison between these diverse metrics, each KPI is
standardized to a common 1–100 scale using PostgreSQL window functions.

Category Performance is evaluated separately by ranking products only against
others within the same category. This prevents products from receiving inflated
scores simply because they belong to a high-revenue category and instead rewards
strong performance relative to direct competitors.

The weighted Product Performance Index provides management with a single,
interpretable score that supports merchandising decisions, pricing strategy,
inventory planning, product promotion, and executive dashboard reporting.

The final scorecard is designed as a reusable analytical dataset suitable for
integration into future Business Intelligence dashboards developed in
