-- ============================================================================
-- QUESTION 9
-- Rank products according to customer review score.
--
-- Products with fewer than 30 reviews are excluded to reduce statistical
-- noise caused by very small sample sizes.
-- ============================================================================

WITH product_reviews AS
(
    SELECT

        oi.product_id AS product,

        COUNT(orv.review_score) AS review_count,

        ROUND(
            AVG(orv.review_score),
            2
        ) AS average_review_score

    FROM order_items oi

    JOIN order_reviews orv

        ON oi.order_id = orv.order_id

    GROUP BY product

    HAVING COUNT(orv.review_score) >= 30
)

SELECT

    product,

    review_count,

    average_review_score,

    RANK() OVER
    (
        ORDER BY average_review_score DESC
    ) AS review_rank

FROM product_reviews

ORDER BY review_rank;


