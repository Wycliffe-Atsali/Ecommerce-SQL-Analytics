-- ============================================================================
-- CATEGORY PERFORMANCE SCORING
--
-- Products are evaluated against competitors within the SAME category.
--
-- Instead of rewarding products simply because they belong to a successful
-- category, each product is compared only with similar products.
--
-- NTILE(100) converts revenue into percentile scores ranging from 1–100.
--
-- ASCENDING ORDER:
--
-- Lowest revenue  → Lowest score
-- Highest revenue → Highest score
--
-- This category score will become one component of the final weighted
-- Product Performance Score.
-- ============================================================================

WITH category_performance AS
(
    SELECT

        p.product_id AS product,

        p.product_category_name AS category,

        SUM(oi.price) AS revenue,

        NTILE(100) OVER
        (
            PARTITION BY p.product_category_name
            ORDER BY SUM(oi.price) ASC
        ) AS category_score

    FROM products p

    JOIN order_items oi

        ON p.product_id = oi.product_id

    GROUP BY
        p.product_id,
        p.product_category_name
)

SELECT *

FROM category_performance

ORDER BY
    category,
    category_score DESC;


